#!/usr/bin/env node
// vmu glossary table — `vibe-math-vmu/glossary.json` is the SINGLE SOURCE; docs/01-§7 is GENERATED from it.
//
// WHY: 22 design volumes later, the same concept is spelled several ways and two volumes can define the same
// term differently (the 08↔17 review found exactly that class of drift). A machine-readable glossary plus a
// generated table plus a two-sided test makes the vocabulary a fact instead of a habit - and it is what a
// translator needs for the multilingual track.
//
//   node scripts/generate-glossary-table.mjs --write   # refresh the generated section
//   node scripts/generate-glossary-table.mjs --check   # fail (exit 1) if it is stale
//   node scripts/generate-glossary-table.mjs --json     # machine view
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const GLOSSARY = process.env.VMU_GLOSSARY ? resolve(process.env.VMU_GLOSSARY) : join(REPO, 'vibe-math-vmu', 'glossary.json')
const DOC = process.env.VMU_GLOSSARY_DOC
  ? resolve(process.env.VMU_GLOSSARY_DOC)
  : join(REPO, 'vibe-math-vmu', 'docs', '01-philosophy.md')
export const BEGIN = '<!-- GLOSSARY:BEGIN (generated by scripts/generate-glossary-table.mjs — do not hand-edit) -->'
export const END = '<!-- GLOSSARY:END -->'

/** Read and validate the glossary. Throws on malformed input: a silent skip would hide a broken vocabulary. */
export function readGlossary(path = GLOSSARY) {
  const raw = JSON.parse(readFileSync(path, 'utf8'))
  if (!raw || !Array.isArray(raw.terms) || raw.terms.length === 0) throw new Error('glossary has no terms')
  const ids = new Set()
  for (const t of raw.terms) {
    for (const f of ['id', 'zh', 'en', 'layer', 'definedIn', 'note']) {
      if (typeof t[f] !== 'string' || t[f].length === 0) throw new Error('term ' + (t.id || '?') + ' lacks ' + f)
    }
    if (ids.has(t.id)) throw new Error('duplicate term id: ' + t.id)
    ids.add(t.id)
  }
  return raw
}

/** The generated section: one row per term, stable order (the file order IS the order - no sorting surprise). */
export function renderTable(glossary) {
  const rows = glossary.terms.map((t) => '| **' + t.zh + ' / ' + t.en + '** | `' + t.layer + '` | ' + t.definedIn + ' | ' + t.note + ' |')
  return [
    BEGIN,
    '',
    '> **本表由 `vibe-math-vmu/glossary.json` 生成 ✓**（`scripts/generate-glossary-table.mjs` ✓）：',
    '> 术语的**单一真源是那个 JSON** ✓，本文只是人读视图 ✓；`tests/audit-vmu-glossary.test.mjs` 守双向一致 ✓。',
    '> **定义归属**（`definedIn` 列 ✓）是硬约定 ✓：**其它卷只能引用、不得重新定义** ✗（08↔17 的重复登记就是这么发现的 ✓）。',
    '',
    '| 术语 | 层 | 定义归属 | 一句话 |',
    '|---|---|---|---|',
    ...rows,
    '',
    END,
  ].join('\n')
}

export function splitDoc(text) {
  const b = text.indexOf(BEGIN)
  const e = text.indexOf(END)
  if (b === -1 || e === -1 || e < b) return { head: text, tail: '' }
  return { head: text.slice(0, b), tail: text.slice(e + END.length) }
}

const isMain = process.argv[1] && process.argv[1].endsWith('generate-glossary-table.mjs')
if (isMain) {
  const glossary = readGlossary()
  const block = renderTable(glossary)
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify({ terms: glossary.terms.length, layers: [...new Set(glossary.terms.map((t) => t.layer))], glossary }, null, 1))
    process.exit(0)
  }
  const text = readFileSync(DOC, 'utf8')
  const { head, tail } = splitDoc(text)
  if (head === text) {
    console.error('glossary table: STALE — docs/01 has no GLOSSARY markers (add them once, then --write)')
    process.exit(1)
  }
  const next = head.replace(/\s*$/, '\n\n') + block + '\n' + tail.replace(/^\s*/, '\n')
  console.log('glossary terms=' + glossary.terms.length)
  if (next === text) { console.log('glossary table: up to date (' + glossary.terms.length + ' terms)'); process.exit(0) }
  if (process.argv.includes('--write')) {
    writeFileSync(DOC, next, 'utf8')
    console.log('glossary table: REWRITTEN (' + glossary.terms.length + ' terms)')
    process.exit(0)
  }
  console.error('glossary table: STALE — docs/01-§7 is not what the glossary yields')
  console.error('run: node scripts/generate-glossary-table.mjs --write')
  process.exit(1)
}
