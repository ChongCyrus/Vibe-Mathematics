export function collect() {
  const files = readdirSync(KERNEL).filter((f) => f.endsWith('.js'))
  // Keys already declared in the schema must NOT be added again. Measured: `records.js` distinguishes
  // `WIRED_KEYS` (its documented keys) from `EXTRA_WIRED_KEYS` ("the registered core keys this module also
  // reads"), and all twenty-four of the latter were already in schema.js - re-adding them produced 24 duplicate
  // entries and broke the uniqueness invariant three gates check.
  const already = new Set()
  try {
    // The scan must ignore MY OWN generated block, or the generator is not idempotent: on the second run every
    // key it emitted last time would look "already declared" and the block would empty itself out. Measured:
    // that made the regeneration chain report 7/8 in sync with nothing to write.
    let schemaSrc = readFileSync(SCHEMA, 'utf8')
    const b = schemaSrc.indexOf(BEGIN)
    if (b !== -1) { const e = schemaSrc.indexOf(END, b); if (e !== -1) schemaSrc = schemaSrc.slice(0, b) + schemaSrc.slice(e + END.length) }
    // ROUND 606 — THE SAME BUG AS ROUND 604, IN TWO MORE PLACES. `key: '([^']+)'` matches ANY `key: '...'` in the file, including a
    // source line whose template expression happens to contain one: measured here as 1039 captures of which one is the fragment
    // `" + key,\n      "`. A settings key is a dotted `vmu.*` path, so the declaration's own shape is the criterion - anything else is
    // code. Left unfiltered, a bogus "already declared" entry can make a real key look pre-existing and be skipped.
    const KEY_SHAPE = /^vmu\.[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*$/
    for (const m of schemaSrc.matchAll(/key:\s*'([^']+)'/g)) if (KEY_SHAPE.test(m[1])) already.add(m[1])
    for (const m of schemaSrc.matchAll(/key:\s*"([^"]+)"/g)) if (KEY_SHAPE.test(m[1])) already.add(m[1])
  } catch (e) { /* no schema yet: nothing is declared */ }
  const out = []
  const perModule = []
  const skipped = []
  const preexisting = []
  const handDeclared = []
  for (const f of files) {
    const src = readFileSync(join(KERNEL, f), 'utf8')
    // A module is scanned if it EXPORTS a list or if it READS any key: the second half is the round-81 fix for
    // the blind spot where a face read its settings through an accessor and never exported a list.
    // ROUND 113: ask the LIST function whether it found anything instead of testing for a literal export name.
    // The substring test missed `WIRED_<FACE>_KEYS` (ballot box, course, resource, store policy), so those
    // four faces were scanned for accessor forms only - and a key that lives in an exported list is invisible
    // to that scan. Nine keys stayed planned for that reason while their own modules listed them as wired.
    const listed = wiredKeysOf(src)
    // ROUND 281: a UNION, not a fallback. The header states it: a key the code reads IS wired. Using the exported list INSTEAD of the
  // read keys made every other read invisible in a face that exports one - measured: `records.js` exports 24 and reads three more
  // (`vmu.data.*` twice and the rebuttal declaration), none of which this generator could see.
  const keys = [...new Set([...listed, ...readKeysOf(src)])]
    if (!keys.length) continue
    let recovered = 0
    for (const key of keys) {
      if (SERVICE_SURFACES.has(key)) { skipped.push(key); continue }
      // ROUND 17: a hand-declared DOMAIN key is never emitted (see HAND_DECLARED_DOMAINS) - emitting it would write
      // `type:'string'` over the domain. It must instead be declared by hand; the invariant below reddens if it is not.
      // ★ It is therefore PRE-EXISTING BY CONSTRUCTION, and it must be recorded as such: the wired-union gate accounts
      // a module's reads against exactly two sets (the keys emitted for THAT module, and `preexisting`), so a `continue`
      // here made `meetings.js` read a key the union could not account for - measured: 1 violation the moment the
      // `vmu.meetings.orderMode` row moved out of the generated block and into the hand-written schema.
      if (HAND_DECLARED_DOMAINS.has(key)) { handDeclared.push(key); preexisting.push(key); continue }
      if (already.has(key)) { preexisting.push(key); continue }
      const lit = defaultOf(src, key)
      if (lit !== undefined) recovered++
      out.push({ key, module: f, literal: lit === undefined ? null : lit, type: typeOf(lit) })
    }
    perModule.push({ module: f, keys: keys.length, recovered })
  }
  out.sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0)
  // ★ R21: ONE KEY, ONE ROW - AND THE ROW THAT KNOWS ITS DEFAULT WINS. A module that READS a key but obtains its
  // default by import (rather than declaring the literal itself) now yields a second row for the same key with
  // `literal: null`. That is exactly what happened when the meetings face's data tables moved into a companion
  // module: the declaring module still yields the literal, while the reader yields null, and the block ended up
  // declaring the key twice - which the invariant below correctly refuses. The fix is NOT to record these keys in
  // EFFECTIVE_DEFAULTS (that table means "the default genuinely cannot be inferred", and these defaults ARE known -
  // filing them there would be a false name), and NOT to re-inline the data (the split is the point). It is to keep
  // the row that carries the literal and drop the null duplicate, so attribution still points at the declaring
  // module. Order-independent by construction because it runs after the sort.
  {
    const byKey = new Map()
    for (const d of out) {
      const prev = byKey.get(d.key)
      if (!prev) { byKey.set(d.key, d); continue }
      // ★ A DUPLICATE IS FOUND. TWO THINGS MUST HAPPEN, AND THE SECOND ONE IS EASY TO FORGET.
      // (1) The block keeps ONE row, and the row that CARRIES THE LITERAL is the one that knows the default, so it
      //     wins; the module that only READS the key (obtaining the default by import) does not contribute a row.
      // (2) But the reading module still READS the key, and the wired-union gate checks each module's reads against
      //     the keys emitted FOR THAT MODULE plus `preexisting`. Dropping its row without recording it left
      //     `meetings.js` reading keys nothing could account for - measured: a page of VIOLATION lines. So the key is
      //     pushed into `preexisting`, the same bucket this extractor already uses for keys it deliberately does not
      //     emit. Note this runs on EVERY duplicate path, not only the one where the earlier row wins: the branch
      //     structure below has `continue`s, and an appended statement would have been skipped in exactly the branch
      //     that needed it most.
      preexisting.push(d.key)
      const prevHas = prev.literal !== null && prev.literal !== undefined
      const dHas = d.literal !== null && d.literal !== undefined
      if (!prevHas && dHas) byKey.set(d.key, d)
    }
    out.length = 0
    out.push(...byKey.values())
  }
  return { defs: out, perModule, skipped, preexisting, handDeclared }
}

