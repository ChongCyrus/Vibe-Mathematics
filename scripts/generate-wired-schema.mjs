#!/usr/bin/env node
/**
 * WIRED SCHEMA (round 69) — put the keys kernel modules REALLY READ into the core schema.
 *
 * WHY (measured, rounds 67-68): twelve modules export `WIRED_KEYS` - two hundred and seventy keys they read on
 * every call - and `settings/schema.js` declared none of them. The planned registry was covering for that by
 * labelling implemented keys "not yet implemented", so the gates were measuring a LABEL rather than the truth.
 * The generator that writes planned.js excludes keys present in `schema.js` (its `coreKeys()`), so adding them
 * here retires them there: the two steps are one change, which is exactly why doing only the other half reddened
 * three gates in round 67.
 *
 * HOW THE DEFAULT IS OBTAINED: from the module's OWN source, never invented. Four accessor shapes are known:
 *   sget('k', <lit>) · raw(settings, 'k', <lit>) · b/n('k', <lit>) · an object-literal table `'k': <lit>`
 * A key whose default cannot be recovered is emitted with `def: null` and a doc that SAYS SO - a missing default
 * is recorded, not guessed.
 *
 * USAGE: node scripts/generate-wired-schema.mjs [--write]   (without --write it only reports)
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '..')
const KERNEL = join(REPO, 'vibe-math-vmu', 'kernel')
const SCHEMA = join(REPO, 'vibe-math-vmu', 'settings', 'schema.js')
const BEGIN = '  // WIRED-SCHEMA:BEGIN (generated by scripts/generate-wired-schema.mjs - do not hand-edit)'
const END = '  // WIRED-SCHEMA:END'

/** The key list a module exports: an inline freeze, or a `DECLARED_KEYS` array it freezes. */
export function wiredKeysOf(src) {
  const inline = /export const WIRED_KEYS = Object\.freeze\(\[([\s\S]*?)\]\)/.exec(src)
  if (inline) return [...inline[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
  const decl = /const DECLARED_KEYS = Object\.freeze\(\[([\s\S]*?)\]\)/.exec(src) || /const DECLARED_KEYS = \[([\s\S]*?)\]/.exec(src)
  return decl ? [...decl[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []
}

/**
 * ROUND 81: the keys a module actually READS, whatever accessor form it uses. Measured reason: forty-six keys
 * were read on every call yet still labelled "not yet implemented", in modules that never export `WIRED_KEYS` -
 * the exported list was the generator's only source, so those files were a blind spot. A key the code reads IS
 * wired, and the registry must say so.
 */
export const READ_FORMS = [
  /sget\(\s*'([^']+)'/g,
  /raw\(\s*settings\s*,\s*'([^']+)'/g,
  /readKey\(\s*'([^']+)'/g,
  /\bb\(\s*'([^']+)'/g,
  /\bn\(\s*'([^']+)'/g,
  /settings\[\s*'([^']+)'\s*\]/g,
  /settings\[\s*"([^"]+)"\s*\]/g,
]
export function readKeysOf(src) {
  const out = new Set()
  for (const re of READ_FORMS) for (const m of src.matchAll(re)) if (/^vmu\.[a-z0-9]+\./.test(m[1])) out.add(m[1])
  return [...out]
}

/**
 * The literal default for one key, recovered from the module's own source. `undefined` = not recoverable.
 * The capture is the REST OF THE LINE and is then trimmed, because a bracketed literal contains commas
 * (`['title', 'abstract']`) and a `[^,\n]+` capture would stop inside it - measured: that produced `['title'`
 * and a syntax error in the generated schema, which is why the trim exists.
 */
export function defaultOf(src, key) {
  const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  // A module may keep a short alias for a long key and store defaults under a COMPUTED key: `records.js` maps
  // `headMaxItems: 'vmu.records.head.maxItems'` and then writes `[K.headMaxItems]: 200`. Resolve the alias first.
  const alias = new RegExp("([A-Za-z_$][\\w$]*)\\s*:\\s*['\"]" + esc + "['\"]").exec(src)
  // A value may be a scalar, a bracketed list/object (which CONTAINS commas) or a quoted string - and the table
  // may put SEVERAL entries on one line (`'k': 30, 'k2': 7,`). Measured: capturing to end-of-line swallowed the
  // next entry and the literal was rejected as invalid, so the pair of entries was reported unrecoverable.
  const VAL = "(\\[[^\\]]*\\]|\\{[^}]*\\}|'[^']*'|\"[^\"]*\"|[^,\\n]+)"
  const S = "settings\\[\\s*['\"]" + esc + "['\"]\\s*\\]"
  const shapes = [
    new RegExp("(?:sget|b|n)\\(\\s*'" + esc + "'\\s*,\\s*" + VAL + "\\s*\\)"),          // sget('k', 5)
    new RegExp("raw\\(\\s*settings\\s*,\\s*'" + esc + "'\\s*,\\s*" + VAL + "\\s*\\)"), // raw(settings, 'k', true)
    new RegExp("[\"']" + esc + "[\"']\\s*:\\s*" + VAL),                                // an object-literal table
    // A coercing helper's SECOND argument is the fallback the module really uses when the setting is absent.
    new RegExp("(?:intOr|nat|numOr|listOr|listOf|boolOf)\\s*\\(\\s*" + S + "\\s*,\\s*" + VAL + "\\s*\\)"),
    // A TERNARY whose condition names the setting: the ELSE branch is the absent-value answer. Two shapes are
    // common - an enum guard (`POLICIES.includes(settings['k']) ? settings['k'] : 'refresh'`) and a type guard
    // (`Array.isArray(settings['k']) ? settings['k'] : []`). The else is read off the code, never invented.
    new RegExp("[\\w.]+\\.includes\\(\\s*" + S + "\\s*\\)\\s*\\?[^:]*:\\s*" + VAL),
    new RegExp("Array\\.isArray\\(\\s*" + S + "\\s*\\)\\s*\\?[^:]*:\\s*" + VAL),
    new RegExp(S + "[^?\\n]*\\?[^:\\n]*:\\s*" + VAL),
  ]
  if (alias) shapes.push(new RegExp("\\[\\s*K\\." + alias[1] + "\\s*\\]\\s*:\\s*" + VAL)) // [K.alias]: <lit>
  /**
   * The value a module uses when a setting is ABSENT may be expressed as a COMPARISON rather than a default
   * argument - `external.js` does exactly that. These answers are read off the expression, never guessed:
   * `!== false` is true when absent, `=== true` is false, a `str(...)` wrapper is the empty string. They are
   * consulted only AFTER the literal shapes, so a table entry always wins over an inference.
   */
  const CONST_ANSWERS = [
    [new RegExp(S + "\\s*!==\\s*false"), 'true'],
    [new RegExp(S + "\\s*===\\s*true"), 'false'],
    [new RegExp("(?:str|String)\\(\\s*" + S + "\\s*\\)"), "''"],
    // `listOr(x)` with no fallback yields an empty list: the module's own helper is the authority for that.
    [new RegExp("(?:listOr|listOf)\\(\\s*" + S + "\\s*\\)"), '[]'],
  ]
  for (const re of shapes) {
    const m = re.exec(src)
    if (m && m[1] !== undefined) {
      let lit = m[1].trim()
      // trim a trailing call/array/comma tail: `['a','b'],` -> `['a','b']`; `true }` -> `true`
      lit = lit.replace(/[\s,;]+$/, '')
      if (lit.startsWith('[') && !lit.endsWith(']')) { const close = lit.lastIndexOf(']'); if (close !== -1) lit = lit.slice(0, close + 1) }
      if (lit.startsWith('{') && !lit.endsWith('}')) { const close = lit.lastIndexOf('}'); if (close !== -1) lit = lit.slice(0, close + 1) }
      // A numeric expression is a literal too: `external.js` writes `1 << 20`. Only digits, a shift and
      // parentheses are accepted, and the shift is evaluated by hand - `eval` is never used on source text.
      const shift = /^\(?\s*(\d+)\s*(<<|>>)\s*(\d+)\s*\)?$/.exec(lit)
      if (shift) {
        const base = Number(shift[1])
        const by = Number(shift[3])
        const value = shift[2] === '<<' ? base * Math.pow(2, by) : Math.floor(base / Math.pow(2, by))
        if (Number.isFinite(value)) lit = String(value)
      }
      // A numeric literal may carry separators (`3_600_000`) or scientific notation (`1e-6`); both are cosmetic.
      if (/^\d[\d_]*$/.test(lit)) lit = lit.replace(/_/g, '')
      // A two-operand arithmetic default (`7 * 86400000`) is evaluated by hand: digits and one operator only,
      // never `eval`. Anything richer is left unrecovered rather than guessed.
      const arith = /^(\d[\d_]*)\s*([*/+-])\s*(\d[\d_]*)$/.exec(lit)
      if (arith) {
        const a = Number(arith[1].replace(/_/g, ''))
        const b = Number(arith[3].replace(/_/g, ''))
        const v = arith[2] === '*' ? a * b : arith[2] === '/' ? a / b : arith[2] === '+' ? a + b : a - b
        if (Number.isFinite(v)) lit = String(v)
      }
      if (/^(true|false|null)$/.test(lit) || /^-?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(lit) || /^['"]/.test(lit)
        || (lit.startsWith('[') && lit.endsWith(']')) || (lit.startsWith('{') && lit.endsWith('}'))) return lit
    }
  }
  // Only now: a comparison/wrapper expresses the absent-value answer directly (see CONST_ANSWERS above).
  for (const [re, answer] of CONST_ANSWERS) if (re.test(src)) return answer
  return undefined
}

/** `type` from the literal's own form, restricted to the types schema.js already uses (never a new one). */
export function typeOf(lit) {
  if (lit === undefined) return null
  const s = lit.trim()
  if (/^(true|false)$/.test(s)) return 'boolean'
  if (/^-?\d+$/.test(s)) return Number(s) >= 0 ? 'natural' : 'natural'
  if (/^-?\d*\.\d+$/.test(s)) return 'ratio'
  if (/^\[/.test(s)) return /\[\s*\{/.test(s) ? 'objectList' : 'stringList'
  if (/^\{/.test(s)) return 'object'
  if (/^'/.test(s) || /^"/.test(s)) return 'string'
  return null
}

/**
 * SERVICE SURFACES are not settings. `ip.js` says it outright: "THE 20 DECLARED KEYS = 15 KNOBS + 5 SERVICE
 * SURFACES" - `hold`/`ownership`/`contributors`/`recordSearch`/`transfer` are the names of service methods, and
 * putting them in the settings schema would claim they are tunable. They stay out, with the reason here.
 */
export const SERVICE_SURFACES = new Set([
  'vmu.ip.hold', 'vmu.ip.ownership', 'vmu.ip.contributors', 'vmu.ip.recordSearch', 'vmu.ip.transfer',
])

export function collect() {
  const files = readdirSync(KERNEL).filter((f) => f.endsWith('.js'))
  // Keys already declared in the schema must NOT be added again. Measured: `records.js` distinguishes
  // `WIRED_KEYS` (its documented keys) from `EXTRA_WIRED_KEYS` ("the registered core keys this module also
  // reads"), and all twenty-four of the latter were already in schema.js - re-adding them produced 24 duplicate
  // entries and broke the uniqueness invariant three gates check.
  const already = new Set()
  try {
    // The scan must ignore MY OWN generated block, or the generator is not idempotent: on the second run every
    // key it emitted last time would look "already declared" and the block would empty itself out. Measured:
    // that made the regeneration chain report 7/8 in sync with nothing to write.
    let schemaSrc = readFileSync(SCHEMA, 'utf8')
    const b = schemaSrc.indexOf(BEGIN)
    if (b !== -1) { const e = schemaSrc.indexOf(END, b); if (e !== -1) schemaSrc = schemaSrc.slice(0, b) + schemaSrc.slice(e + END.length) }
    for (const m of schemaSrc.matchAll(/key:\s*'([^']+)'/g)) already.add(m[1])
    for (const m of schemaSrc.matchAll(/key:\s*"([^"]+)"/g)) already.add(m[1])
  } catch (e) { /* no schema yet: nothing is declared */ }
  const out = []
  const perModule = []
  const skipped = []
  const preexisting = []
  for (const f of files) {
    const src = readFileSync(join(KERNEL, f), 'utf8')
    // A module is scanned if it EXPORTS a list or if it READS any key: the second half is the round-81 fix for
    // the blind spot where a face read its settings through an accessor and never exported a list.
    const exported = src.includes('export const WIRED_KEYS')
    const keys = exported ? wiredKeysOf(src) : readKeysOf(src)
    if (!keys.length) continue
    let recovered = 0
    for (const key of keys) {
      if (SERVICE_SURFACES.has(key)) { skipped.push(key); continue }
      if (already.has(key)) { preexisting.push(key); continue }
      const lit = defaultOf(src, key)
      if (lit !== undefined) recovered++
      out.push({ key, module: f, literal: lit === undefined ? null : lit, type: typeOf(lit) })
    }
    perModule.push({ module: f, keys: keys.length, recovered })
  }
  out.sort((a, b) => a.key < b.key ? -1 : a.key > b.key ? 1 : 0)
  return { defs: out, perModule, skipped, preexisting }
}

export function render(defs) {
  const lines = [BEGIN]
  for (const d of defs) {
    const def = d.literal === null ? 'null' : d.literal
    const type = d.type === null ? 'object' : d.type
    const doc = d.literal === null
      ? '已接线（' + d.module + ' 读取）；默认值未从源码取回 ⇒ 未定，见该模块'
      : '已接线（' + d.module + ' 读取）；默认值取自模块源码'
    lines.push("  { key: '" + d.key + "', type: '" + type + "', def: " + def + ", hot: HOT.H1, who: 'office', doc: " + JSON.stringify(doc) + ' },')
  }
  lines.push(END)
  return lines.join('\n')
}

export function splice(schemaText, block) {
  const b = schemaText.indexOf(BEGIN)
  if (b !== -1) {
    const e = schemaText.indexOf(END, b)
    if (e === -1) throw new Error('WIRED-SCHEMA:BEGIN without END')
    return schemaText.slice(0, b) + block + schemaText.slice(e + END.length)
  }
  // first run: insert right before the closing `])` of CORE_DEFS
  const close = /\n\]\)\n/.exec(schemaText)
  if (!close) throw new Error('CORE_DEFS closing bracket not found')
  return schemaText.slice(0, close.index) + '\n' + block + schemaText.slice(close.index)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const write = process.argv.includes('--write')
  const { defs, perModule, skipped } = collect()
  for (const m of perModule) console.log('  ' + m.module.padEnd(16) + ' keys=' + String(m.keys).padStart(3) + '  default recovered=' + m.recovered)
  const missing = defs.filter((d) => d.literal === null)
  console.log('  TOTAL keys=' + defs.length + ' recovered=' + (defs.length - missing.length) + ' missing=' + missing.length
    + '  service-surfaces-skipped=' + skipped.length + ' (' + skipped.join(', ') + ')')
  for (const d of missing.slice(0, 10)) console.log('       NO-DEFAULT ' + d.key + '  (' + d.module + ')')
  const schemaText = readFileSync(SCHEMA, 'utf8')
  const next = splice(schemaText, render(defs))
  const stale = next !== schemaText
  console.log('  schema ' + (stale ? (write ? 'REWRITTEN' : 'DRIFT') : 'already in sync') + ' (' + schemaText.split('\n').length + ' -> ' + next.split('\n').length + ' lines)')
  if (write && stale) writeFileSync(SCHEMA, next)
  // `--check` is what the regeneration chain calls: drift must be a FAILURE, not a printout.
  if (!write && stale) { console.log('  DRIFT: settings/schema.js is not what the modules yield - run with --write'); process.exitCode = 1 }
  if (write && stale) console.log('  WROTE ' + defs.length + ' wired keys into ' + SCHEMA)

  // INVARIANTS (round 79, fixed round 81): checked against the text that WILL BE / HAS BEEN written (`next`),
  // never against the pre-write copy - reading the stale copy made every freshly emitted key look like it was
  // missing its doc, which is how thirteen false violations appeared the first time the scan was widened.
  const problems = []
  const blockKeys = defs.map((d) => d.key)
  if (new Set(blockKeys).size !== blockKeys.length) problems.push('the block declares a key twice')
  const preexisting = new Set()
  {
    let without = next
    const b = without.indexOf(BEGIN)
    if (b !== -1) { const e = without.indexOf(END, b); if (e !== -1) without = without.slice(0, b) + without.slice(e + END.length) }
    for (const m of without.matchAll(/key:\s*['"]([^'"]+)['"]/g)) preexisting.add(m[1])
  }
  for (const d of defs) {
    // The doc rule is checked against the FILE, not against this script's own output: `render([d])` would always
    // contain the marker, which made the check unfailable - a vacuous assertion of exactly the kind this project
    // hunts. Measured: with `render` the negative case (marker removed from the file) stayed green.
    const line = next.split('\n').find((l) => l.includes("'" + d.key + "'"))
    if (d.literal === null && !(line && /未从源码取回/.test(line))) problems.push(d.key + ' has no default AND the file does not say so')
    if (preexisting.has(d.key)) problems.push(d.key + ' is declared both in the block and in the hand-written schema')
  }
  // Nothing may be silently dropped: every wired key is emitted, pre-existing, or a documented service surface.
  const emitted = new Set(blockKeys)
  for (const m of perModule) {
    const src = readFileSync(join(KERNEL, m.module), 'utf8')
    // Same source as the collection: exported list OR actual reads, so the blind spot cannot reappear.
    const scanned = src.includes('export const WIRED_KEYS') ? wiredKeysOf(src) : readKeysOf(src)
    for (const k of scanned) {
      if (emitted.has(k) || preexisting.has(k) || skipped.includes(k)) continue
      problems.push(m.module + ' reads ' + k + ' but it is neither declared nor documented as a service surface')
    }
  }
  if (problems.length) {
    for (const p of problems.slice(0, 10)) console.log('  INVARIANT VIOLATED: ' + p)
    console.log('  INVARIANTS: ' + problems.length + ' problem(s)')
    process.exitCode = 1
  } else {
    console.log('  INVARIANTS ok: ' + defs.length + ' emitted, ' + preexisting.size + ' pre-existing, ' + skipped.length + ' service surfaces, ' + missing.length + ' with an honest null default')
  }
}
