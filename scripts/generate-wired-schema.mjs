/**
 * WIRED SCHEMA (round 69) — put the keys kernel modules REALLY READ into the core schema.
 *
 * WHY (measured, rounds 67-68): twelve modules export `WIRED_KEYS` - two hundred and seventy keys they read on
 * every call - and `settings/schema.js` declared none of them. The planned registry was covering for that by
 * labelling implemented keys "not yet implemented", so the gates were measuring a LABEL rather than the truth.
 * The generator that writes planned.js excludes keys present in `schema.js` (its `coreKeys()`), so adding them
 * here retires them there: the two steps are one change, which is exactly why doing only the other half reddened
 * three gates in round 67.
 *
 * HOW THE DEFAULT IS OBTAINED: from the module's OWN source, never invented. Four accessor shapes are known:
 *   sget('k', <lit>) · raw(settings, 'k', <lit>) · b/n('k', <lit>) · an object-literal table `'k': <lit>`
 * A key whose default cannot be recovered is emitted with `def: null` and a doc that SAYS SO - a missing default
 * is recorded, not guessed.
 *
 * USAGE: node scripts/generate-wired-schema.mjs [--write]   (without --write it only reports)
 *        node scripts/generate-wired-schema.mjs --selftest  (the KEY_SHAPE / comment self-probe only)
 */
