/**
 * ROUND 3 (task-23): A SETTINGS KEY HAS A SHAPE, SO THE EXTRACTION CHECKS IT.
 *
 * WHY (measured): `kernel/paper.js` kept the C-30 rationale in a comment that QUOTED key names, and this
 * generator read the quoted text as a real key - `exit=1` until a human rewrote the comment. That is the same
 * "parse by text, ignore context" defect class as the hook scan: the gate was green only because nobody had
 * written a key-looking string in prose. Two fixes, both here:
 *   ① every candidate is filtered by KEY_SHAPE (a real key is `vmu.<lower-namespace>.<something>`);
 *   ② the source is COMMENT-BLANKED before extraction (strings KEPT - the keys live in string literals, so
 *      `strings:true` would erase exactly what we are reading).
 * A pseudo-key in prose can no longer enter the schema, and the self-probe below proves it stays out.
 */
export const KEY_SHAPE = /^vmu\.[a-z][a-z0-9]*(\.[A-Za-z0-9_]+)+$/
/** Key literals inside a source fragment: comments blanked, string contents kept, then shape-filtered. */
export function extractKeyLiterals(fragment) {
  const live = stripComments(String(fragment == null ? '' : fragment))
  return [...live.matchAll(/'([^']+)'/g)].map((m) => m[1]).filter((k) => KEY_SHAPE.test(k))
}
const KERNEL = join(REPO, 'vibe-math-vmu', 'kernel')
const SCHEMA = join(REPO, 'vibe-math-vmu', 'settings', 'schema.js')
const BEGIN = '  // WIRED-SCHEMA:BEGIN (generated by scripts/generate-wired-schema.mjs - do not hand-edit)'
const END = '  // WIRED-SCHEMA:END'

/** The key list a module exports: an inline freeze, or a `DECLARED_KEYS` array it freezes. */
export function wiredKeysOf(src) {
  // ROUND 111: four faces name their wired list `WIRED_<FACE>_KEYS` (ballot box, course, resource, store
  // policy) and keep a SEPARATE `PLANNED_<FACE>_KEYS` with a reason per key. Recognising only the two generic
  // names left every one of those keys unregistered, so the registry called them planned while the module
  // itself listed them as wired - measured: nineteen keys across four faces.
  const face = /export const WIRED_[A-Z_]+_KEYS = Object\.freeze\(\[([\s\S]*?)\]\)/.exec(src)
  if (face) return extractKeyLiterals(face[1])
  const alias = /export const WIRED_[A-Z_]+_KEYS = ([A-Z_]+_KEYS)\b/.exec(src)
  if (alias) {
    const base = new RegExp('export const ' + alias[1] + ' = Object\\.freeze\\(\\[([\\s\\S]*?)\\]\\)').exec(src)
    if (base) return extractKeyLiterals(base[1])
  }
  const inline = /export const WIRED_KEYS = Object\.freeze\(\[([\s\S]*?)\]\)/.exec(src)
  if (inline) return extractKeyLiterals(inline[1])
  const decl = /const DECLARED_KEYS = Object\.freeze\(\[([\s\S]*?)\]\)/.exec(src) || /const DECLARED_KEYS = \[([\s\S]*?)\]/.exec(src)
  return decl ? extractKeyLiterals(decl[1]) : []
}

/**
 * ROUND 81: the keys a module actually READS, whatever accessor form it uses. Measured reason: forty-six keys
 * were read on every call yet still labelled "not yet implemented", in modules that never export `WIRED_KEYS` -
 * the exported list was the generator's only source, so those files were a blind spot. A key the code reads IS
 * wired, and the registry must say so.
 */
export const READ_FORMS = [
  /sget\(\s*'([^']+)'/g,
  /raw\(\s*settings\s*,\s*'([^']+)'/g,
  /readKey\(\s*'([^']+)'/g,
  /\bb\(\s*'([^']+)'/g,
  /\bn\(\s*'([^']+)'/g,
  /settings\[\s*'([^']+)'\s*\]/g,
  /settings\[\s*"([^"]+)"\s*\]/g,
]
export function readKeysOf(src) {
  // ROUND 3: comments are blanked FIRST (strings kept - the accessor argument IS a string literal). Without this
  // a line like `// sget('vmu.fake.key')` in prose registered a key nobody reads.
  const live = stripComments(String(src == null ? '' : src))
  const out = new Set()
  for (const re of READ_FORMS) for (const m of live.matchAll(re)) if (KEY_SHAPE.test(m[1])) out.add(m[1])
  return [...out]
}

/**
 * ROUND 3 SELF-PROBE (run by `--selftest` and by `tests/audit-generators-current.test.mjs`): the extraction must
 * ignore pseudo-keys that live in COMMENTS while still finding the real ones. Without this, the gate is green
 * only because no human has quoted a key in prose yet - the measured failure mode that reddened this generator.
 */
export function keyShapeProbe() {
  const synthetic = [
    "// the office gate quotes a key in prose: sget('vmu.fake.commentKey')",
    "export const WIRED_KEYS = Object.freeze([",
    "  'vmu.real.wiredKey',",
    "  // a plan note that mentions 'vmu.fake.planNote'",
    "])",
    "const x = sget('vmu.real.readKey')",
  ].join('\n')
  const wired = wiredKeysOf(synthetic)
  const read = readKeysOf(synthetic)
  const shapeRejects = ["'vmu.onegroup'", "'vmu.Upper.key'", "'other.key'", "'vmu.two.'", "'vmu.a..b'", "'vmu.a-b.c'"]
    .map((s) => extractKeyLiterals(s).length === 0)
  return {
    fakeInCommentExcluded: !wired.includes('vmu.fake.planNote') && !read.includes('vmu.fake.commentKey'),
    realStillFound: wired.includes('vmu.real.wiredKey') && read.includes('vmu.real.readKey'),
    shapeRejectsMalformed: shapeRejects.every(Boolean),
    wired, read,
  }
}

/**
 * The literal default for one key, recovered from the module's own source. `undefined` = not recoverable.
 * The capture is the REST OF THE LINE and is then trimmed, because a bracketed literal contains commas
 * (`['title', 'abstract']`) and a `[^,\n]+` capture would stop inside it - measured: that produced `['title'`
 * and a syntax error in the generated schema, which is why the trim exists.
 */
export function defaultOf(src, key) {
  const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  // A module may keep a short alias for a long key and store defaults under a COMPUTED key: `records.js` maps
  // `headMaxItems: 'vmu.records.head.maxItems'` and then writes `[K.headMaxItems]: 200`. Resolve the alias first.
  const alias = new RegExp("([A-Za-z_$][\\w$]*)\\s*:\\s*['\"]" + esc + "['\"]").exec(src)
  // A value may be a scalar, a bracketed list/object (which CONTAINS commas) or a quoted string - and the table
  // may put SEVERAL entries on one line (`'k': 30, 'k2': 7,`). Measured: capturing to end-of-line swallowed the
  // next entry and the literal was rejected as invalid, so the pair of entries was reported unrecoverable.
  const VAL = "(\\[[^\\]]*\\]|\\{[^}]*\\}|'[^']*'|\"[^\"]*\"|[^,\\n]+)"
  /**
   * ROUND 134: `S` used to spell ONE accessor form (`settings['k']`), while modules also read the same setting
   * through `readKey('k')`, `sget('k')` and `raw(settings, 'k')`. Every rule below states a fact about the
   * ABSENT-VALUE ANSWER, not about the spelling of the accessor, so the placeholder now covers the forms the tree
   * really uses. Measured reason: `course.peerWeight` writes `Number(readKey('k')) > 0 ? Number(readKey('k')) : 0`
   * and the ternary rule that reads exactly that answer could not see it, so the key was emitted with a null default
   * while its answer (`0`) is written in the expression.
   */
  const S = "(?:settings\\[\\s*['\"]" + esc + "['\"]\\s*\\]"
    + "|(?:readKey|sget|raw|get|s)\\s*\\(\\s*(?:settings\\s*,\\s*)?['\"]" + esc + "['\"]\\s*\\))"
  const shapes = [
    new RegExp("(?:sget|b|n|s)\\(\\s*'" + esc + "'\\s*,\\s*" + VAL + "\\s*\\)"),         // sget('k', 5) / s('k', 'x')
    new RegExp("raw\\(\\s*settings\\s*,\\s*'" + esc + "'\\s*,\\s*" + VAL + "\\s*\\)"), // raw(settings, 'k', true)
    new RegExp("[\"']" + esc + "[\"']\\s*:\\s*" + VAL),                                // an object-literal table
    // A coercing helper's SECOND argument is the fallback the module really uses when the setting is absent.
    new RegExp("(?:intOr|nat|numOr|listOr|listOf|boolOr|boolOf|strOr)\\s*\\(\\s*" + S + "\\s*,\\s*" + VAL + "\\s*\\)"),
    // `settings['k'] || <lit>` is the same statement in operator form: the right side is the absent-value answer.
    new RegExp(S + "\\s*\\|\\|\\s*" + VAL),
    // A TERNARY whose condition names the setting: the ELSE branch is the absent-value answer. Two shapes are
    // common - an enum guard (`POLICIES.includes(settings['k']) ? settings['k'] : 'refresh'`) and a type guard
    // (`Array.isArray(settings['k']) ? settings['k'] : []`). The else is read off the code, never invented.
    new RegExp("[\\w.]+\\.includes\\(\\s*" + S + "\\s*\\)\\s*\\?[^:]*:\\s*" + VAL),
    new RegExp("Array\\.isArray\\(\\s*" + S + "\\s*\\)\\s*\\?[^:]*:\\s*" + VAL),
    new RegExp(S + "[^?\\n]*\\?[^:\\n]*:\\s*" + VAL),
  ]
  if (alias) shapes.push(new RegExp("\\[\\s*K\\." + alias[1] + "\\s*\\]\\s*:\\s*" + VAL)) // [K.alias]: <lit>
  /**
   * ROUND 133: several faces read their settings through a SHORT HELPER OF THEIR OWN - `course.js` defines
   * `const s = (k, d) => (v === undefined || v === '' ? d : String(v))` and then writes `s('vmu.course.submitMode',
   * 'artifact')`. Requiring a fixed accessor-name list (sget|b|n) could not see that, so two keys whose defaults
   * ARE written in the module were emitted with `def: null`. The rule is stated as a property, not a longer list:
   * ANY function the module itself DEFINES with two or more parameters, called with the key literal first and a
   * literal second, carries that literal as the absent-value answer. That is provable from the source and is not a
   * guess; the known accessors are tried first, so an explicit form always wins, and a one-parameter helper (a pure
   * reader, with no fallback to give) never matches.
   */
  const definedHelpers = new Set()
  for (const m of src.matchAll(/(?:const|let|var|function)\s+([A-Za-z_$][\w$]*)\s*=?\s*(?:async\s+)?(?:function\s*)?\(([^)]*)\)/g)) {
    const params = m[2].split(',').filter((p) => p.trim().length > 0)
    if (params.length >= 2) definedHelpers.add(m[1])
  }
  for (const h of definedHelpers) {
    if (h === 'raw' || h === 'sget') continue // already covered above, with their own precedence
    shapes.push(new RegExp(h + "\\(\\s*'" + esc + "'\\s*,\\s*" + VAL + "\\s*\\)"))
  }
  /**
   * The value a module uses when a setting is ABSENT may be expressed as a COMPARISON rather than a default
   * argument - `external.js` does exactly that. These answers are read off the expression, never guessed:
   * `!== false` is true when absent, `=== true` is false, a `str(...)` wrapper is the empty string. They are
   * consulted only AFTER the literal shapes, so a table entry always wins over an inference.
   */
  const CONST_ANSWERS = [
    [new RegExp(S + "\\s*!==\\s*false"), 'true'],
    [new RegExp(S + "\\s*===\\s*true"), 'false'],
    [new RegExp("(?:str|String)\\(\\s*" + S + "\\s*\\)"), "''"],
    // `listOr(x)` with no fallback yields an empty list: the module's own helper is the authority for that.
    [new RegExp("(?:listOr|listOf)\\(\\s*" + S + "\\s*\\)"), '[]'],
  ]
  for (const re of shapes) {
    const m = re.exec(src)
    if (m && m[1] !== undefined) {
      let lit = m[1].trim()
      // trim a trailing call/array/comma tail: `['a','b'],` -> `['a','b']`; `true }` -> `true`
      lit = lit.replace(/[\s,;]+$/, '')
      if (lit.startsWith('[') && !lit.endsWith(']')) { const close = lit.lastIndexOf(']'); if (close !== -1) lit = lit.slice(0, close + 1) }
      if (lit.startsWith('{') && !lit.endsWith('}')) { const close = lit.lastIndexOf('}'); if (close !== -1) lit = lit.slice(0, close + 1) }
      // A numeric expression is a literal too: `external.js` writes `1 << 20`. Only digits, a shift and
      // parentheses are accepted, and the shift is evaluated by hand - `eval` is never used on source text.
      const shift = /^\(?\s*(\d+)\s*(<<|>>)\s*(\d+)\s*\)?$/.exec(lit)
      if (shift) {
        const base = Number(shift[1])
        const by = Number(shift[3])
        const value = shift[2] === '<<' ? base * Math.pow(2, by) : Math.floor(base / Math.pow(2, by))
        if (Number.isFinite(value)) lit = String(value)
      }
      // A numeric literal may carry separators (`3_600_000`) or scientific notation (`1e-6`); both are cosmetic.
      if (/^\d[\d_]*$/.test(lit)) lit = lit.replace(/_/g, '')
      // A two-operand arithmetic default (`7 * 86400000`) is evaluated by hand: digits and one operator only,
      // never `eval`. Anything richer is left unrecovered rather than guessed.
      const arith = /^(\d[\d_]*)\s*([*/+-])\s*(\d[\d_]*)$/.exec(lit)
      if (arith) {
        const a = Number(arith[1].replace(/_/g, ''))
        const b = Number(arith[3].replace(/_/g, ''))
        const v = arith[2] === '*' ? a * b : arith[2] === '/' ? a / b : arith[2] === '+' ? a + b : a - b
        if (Number.isFinite(v)) lit = String(v)
      }
      if (/^(true|false|null)$/.test(lit) || /^-?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(lit) || /^['"]/.test(lit)
        || (lit.startsWith('[') && lit.endsWith(']')) || (lit.startsWith('{') && lit.endsWith('}'))) return lit
      /**
       * ROUND 145: the capture over-runs by the closing parens of an ENCLOSING call - `Number(readKey('k') || 0)`
       * captures `0)`, which fails the literal test and the key is written off as having no default. Measured on
       * `paper.js`: its section cap is written exactly that way and was emitted with an honest null while the
       * default sits in the expression. Retry once with trailing parens stripped, and accept ONLY if what remains
       * is still a literal - so `bar(1))` and `getDefault())` are still rejected (no widening of what counts).
       */
      const stripped = lit.replace(/[)\s]+$/, '')
      if (stripped !== lit
        && (/^(true|false|null)$/.test(stripped) || /^-?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(stripped) || /^['"]/.test(stripped)
          || (stripped.startsWith('[') && stripped.endsWith(']')) || (stripped.startsWith('{') && stripped.endsWith('}')))) {
        return stripped
      }
      /**
       * ROUND 134: an identifier path (`DEFAULTS.fairnessPolicy`) is not a literal, but reading it is not a guess
       * either - the module defines that table in its own source, a few lines above the call. Measured: the auction
       * face writes `sget('vmu.auction.fairnessPolicy', DEFAULTS.fairnessPolicy)` and its three keys were emitted
       * with an honest null while their real defaults (`equal`, `0`, `0`) sat in the frozen table above them. The
       * table is found by its own declaration, the field is read out of it, and only a LITERAL value is accepted -
       * a nested path or a computed field still yields null rather than a guess.
       */
      const path = /^([A-Za-z_$][\w$]*)\s*\.\s*([A-Za-z_$][\w$]*)$/.exec(lit.replace(/[)\s,;]+$/, ''))
      if (path) {
        // The capture over-runs by the closing parens of an enclosing call when the default sits one level deeper
        // (`FAIRNESS_POLICIES.includes(sget('k', DEFAULTS.fairnessPolicy))`), which is the same capture-tail problem
        // the trim above already handles for commas - so the path test trims them too, and only for this test.
        const decl = new RegExp("(?:const|let|var)\\s+" + path[1] + "\\s*=\\s*(?:Object\\.freeze\\(\\s*)?\\{")
        const dm = decl.exec(src)
        if (dm) {
          const body = src.slice(dm.index + dm[0].length)
          const field = path[2].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
          const fm = new RegExp("(?:^|[,{\\s])['\"]?" + field + "['\"]?\\s*:\\s*" + VAL).exec(body)
          if (fm && fm[1] !== undefined) {
            let v = fm[1].trim().replace(/[\s,;]+$/, '')
            if (v.startsWith('[') && !v.endsWith(']')) { const close = v.lastIndexOf(']'); if (close !== -1) v = v.slice(0, close + 1) }
            if (/^(true|false|null)$/.test(v) || /^-?\d+(\.\d+)?$/.test(v) || /^['"]/.test(v)
              || (v.startsWith('[') && v.endsWith(']'))) return v
          }
        }
      }
    }
  }
  // Only now: a comparison/wrapper expresses the absent-value answer directly (see CONST_ANSWERS above).
  for (const [re, answer] of CONST_ANSWERS) if (re.test(src)) return answer
  return undefined
}

/** `type` from the literal's own form, restricted to the types schema.js already uses (never a new one). */
export function typeOf(lit) {
  if (lit === undefined) return null
  const s = lit.trim()
  if (/^(true|false)$/.test(s)) return 'boolean'
  if (/^-?\d+$/.test(s)) return Number(s) >= 0 ? 'natural' : 'natural'
  if (/^-?\d*\.\d+$/.test(s)) return 'ratio'
  // ★ ROUND 30 (task-149 ③, Lead's ruling): SCIENTIFIC NOTATION was unrecognised, so `1e-6` fell through to `null`
  // and the emitter's fallback labelled those rows `type:'object'` while their `def` was a NUMBER — a declaration
  // contradicting its own default (measured: `vmu.math.optim.tolerance`, `vmu.math.precision.tolerance`; the
  // modules read them numerically, e.g. `numf(sget('vmu.math.precision.tolerance'), 1e-9)` in mathtools.js).
  // `number` is the schema's plain-finite-number type and the honest one here.
  if (/^-?\d+(?:\.\d+)?[eE][-+]?\d+$/.test(s)) return 'number'
  if (/^\[/.test(s)) return /\[\s*\{/.test(s) ? 'objectList' : 'stringList'
  if (/^\{/.test(s)) return 'object'
  if (/^'/.test(s) || /^"/.test(s)) return 'string'
  return null
}

