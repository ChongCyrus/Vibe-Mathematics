#!/usr/bin/env node
// vmu planned-code registry — the docs are the single source, `03-§8` stays the single REGISTRY.
//
// WHY: the design volumes declare codes long before they are implemented (85+ at the time of writing), and the
// docs audit requires every `VMU_*` code a volume names to be registered in 03-§8 (gate D14). Hand-copying them
// was a recurring chore that also drifted. So the design-phase codes are GENERATED into a marked block inside
// the contract: the table remains the one place a reader looks, and the block's rows are derived from the docs.
//
//   node scripts/generate-planned-codes.mjs --write   # refresh the block
//   node scripts/generate-planned-codes.mjs --check   # fail (exit 1) if it is stale
//   node scripts/generate-planned-codes.mjs --json     # machine view
//
// RULES (mirroring tests/audit-vmu-docs.test.mjs so the two agree by construction):
//   · codes already registered in the HAND-WRITTEN part of 03-§8 are not repeated;
//   · a FAMILY PREFIX (trailing `_`, e.g. `VMU_ARCHIVE_`) is prose about a namespace, not a code: skipped;
//   · the volume named in the row is the FIRST design volume that mentions the code (deterministic);
//   · the generated-mirror volume (docs/04, produced by the settings-table generator) is never a source.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const REPO = resolve(process.argv[1], '..', '..')
const DOCS = process.env.VMU_DOCS_DIR ? resolve(process.env.VMU_DOCS_DIR) : join(REPO, 'vibe-math-vmu', 'docs')
const CONTRACT = process.env.VMU_CONTRACT ? resolve(process.env.VMU_CONTRACT) : join(DOCS, '03-interface-contract.md')
const BEGIN = '<!-- PLANNED-CODES:BEGIN (generated by scripts/generate-planned-codes.mjs — do not hand-edit) -->'
const END = '<!-- PLANNED-CODES:END -->'
const MIRROR = /^04-/
const CODE = /\b(VMU_[A-Z0-9_]{3,})\b/g

/** Split the contract into the hand-written head and the generated block (empty when the markers are absent). */
export function splitContract(text) {
  const b = text.indexOf(BEGIN)
  const e = text.indexOf(END)
  if (b === -1 || e === -1 || e < b) return { head: text, tail: '' }
  return { head: text.slice(0, b), tail: text.slice(e + END.length) }
}

/** Codes already registered in the hand-written part (any backticked code in the first column of a table row). */
export function handRegistered(head) {
  const out = new Set()
  for (const row of head.matchAll(/^\| ([^|]+)\|/gm)) {
    for (const m of row[1].matchAll(/`(VMU_[A-Z0-9_]+)`/g)) out.add(m[1])
  }
  return out
}

/** Every code the design volumes name, with its first (alphabetical) source volume. */
export function collectPlannedCodes({ docsDir = DOCS, registered = new Set() } = {}) {
  const files = readdirSync(docsDir)
    .filter((f) => /^\d\d-[A-Za-z0-9-]+\.md$/.test(f) && !MIRROR.test(f) && f !== '03-interface-contract.md')
    .sort()
  const found = new Map()
  const families = new Set()
  for (const f of files) {
    const text = readFileSync(join(docsDir, f), 'utf8')
    for (const m of text.matchAll(CODE)) {
      const c = m[1]
      if (registered.has(c)) continue
      // ONLY a trailing-underscore family prefix is "not a code". Exempting names that merely CONTAIN
      // "REASON"/"PACKID" hid real codes (VMU_REASON_REQUIRED) from both this generator and the docs audit.
      if (c.endsWith('_')) { families.add(c); continue }
      if (!found.has(c)) found.set(c, f.slice(0, 2))
    }
  }
  const defs = [...found.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([code, volume]) => ({ code, volume }))
  return { defs, families: [...families].sort() }
}

export function renderBlock(defs) {
  const rows = defs.map((d) => '| `' + d.code + '` | **规划码**（设计阶段登记；语义与触发时机见该卷 ✓，未实现） | 卷 ' + d.volume + ' | ⛔ |')
  return [
    BEGIN,
    '',
    '> **以下为设计阶段登记的计划错误码（生成块 ✓）**：由 `scripts/generate-planned-codes.mjs` 从各设计卷抽取 ✓，',
    '> 与上表同属 **唯一登记表** ✓；**未实现**（`⛔`）⇒ 实现时把它们移入手写上表并补全语义与触发时机 ✓。',
    '',
    '| 码 | 语义 | 来源 | 状态 |',
    '|---|---|---|---|',
    ...rows,
    '',
    END,
  ].join('\n')
}

const isMain = process.argv[1] && process.argv[1].endsWith('generate-planned-codes.mjs')
if (isMain) {
  const text = readFileSync(CONTRACT, 'utf8')
  const { head, tail } = splitContract(text)
  const registered = handRegistered(head)
  const { defs, families } = collectPlannedCodes({ registered })
  const block = renderBlock(defs)
  const next = head.replace(/\s*$/, '\n\n') + block + '\n' + tail.replace(/^\s*/, '\n')
  const mode = process.argv.includes('--write') ? 'write' : process.argv.includes('--check') ? 'check' : 'json'
  if (mode === 'json' || process.argv.includes('--json')) {
    console.log(JSON.stringify({ codes: defs.length, families: families.length, defs }, null, 1))
    process.exit(0)
  }
  console.log('planned codes=' + defs.length + ' (hand-registered=' + registered.size + ', families skipped=' + families.length + ')')
  if (next === text) { console.log('planned codes registry: up to date (' + defs.length + ' planned codes)'); process.exit(0) }
  if (mode === 'write') {
    writeFileSync(CONTRACT, next, 'utf8')
    console.log('planned codes registry: REWRITTEN (' + defs.length + ' planned codes)')
    process.exit(0)
  }
  console.error('planned codes registry: STALE — the contract block is not what the docs yield (' + defs.length + ' planned codes)')
  console.error('run: node scripts/generate-planned-codes.mjs --write')
  process.exit(1)
}
